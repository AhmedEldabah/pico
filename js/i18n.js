function applyLang(lang) {
  const dict = I18N[lang] || I18N.en;
  const html = document.documentElement;
  html.lang = lang;
  html.dir = lang === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] != null) {
      // preserve the year span inside footerRights
      if (key === "footerRights") {
        const y = new Date().getFullYear();
        el.innerHTML = "© " + y + " PICO. " + dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
  });

  // language toggle label shows the OTHER language
  const label = document.getElementById("langLabel");
  if (label) label.textContent = lang === "ar" ? "English" : "العربية";

  try { localStorage.setItem("pico-lang", lang); } catch (e) {}
  window.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
}

window.PICO_I18N = { applyLang, dict: () => I18N[document.documentElement.lang] || I18N.en };
